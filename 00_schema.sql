/* ------------------------------------------------------------
   6. INDEXES

   Every query in all three projects either groups by asset or
   joins on it, so these three indexes cover the whole
   workload.
------------------------------------------------------------ */

CREATE INDEX idx_maintenance_asset ON maintenance (asset_id);
CREATE INDEX idx_production_well   ON production  (well_id);
CREATE INDEX idx_emissions_asset   ON emissions   (asset_id);


/* ------------------------------------------------------------
   7. ASSET CLASS HELPER

   Asset IDs carry their type in the first three characters.
   WEL is a well, PIP is a pipeline, REF is a refinery.

   This matters more than it looks. The production table only
   holds wells, so any join from maintenance to production
   will silently return nothing for pipelines and refineries.
   Without labelling the asset class, a refinery that cost
   half a million dollars to maintain shows up as an asset
   with high spend and zero production, which is wrong. It
   produces no barrels because it is a refinery, not because
   it is failing.
------------------------------------------------------------ */

CREATE OR REPLACE FUNCTION asset_class(p_asset_id TEXT)
RETURNS TEXT AS $$
    SELECT CASE LEFT(p_asset_id, 3)
             WHEN 'WEL' THEN 'Well'
             WHEN 'PIP' THEN 'Pipeline'
             WHEN 'REF' THEN 'Refinery'
             ELSE 'Unknown'
           END;
$$ LANGUAGE SQL IMMUTABLE;


/* ------------------------------------------------------------
   8. SANITY CHECKS

   Run these after loading. If any of them look wrong, stop
   and fix the load before running the analysis.
------------------------------------------------------------ */

-- Row counts. Expect 3000, 5000, 3000.
SELECT 'maintenance' AS table_name, COUNT(*) AS row_count FROM maintenance
UNION ALL
SELECT 'production',  COUNT(*) FROM production
UNION ALL
SELECT 'emissions',   COUNT(*) FROM emissions;


-- How the maintenance events split across asset types.
SELECT
    asset_class(asset_id)    AS asset_type,
    COUNT(*)                 AS maintenance_events,
    COUNT(DISTINCT asset_id) AS distinct_assets
FROM maintenance
GROUP BY 1
ORDER BY maintenance_events DESC;


-- How many maintenance assets can actually be matched to
-- production. Anything below 100 percent is the join key
-- problem described in every project README.
SELECT
    asset_class(m.asset_id)    AS asset_type,
    COUNT(DISTINCT m.asset_id) AS assets_in_maintenance,
    COUNT(DISTINCT p.well_id)  AS assets_found_in_production
FROM maintenance m
LEFT JOIN production p ON m.asset_id = p.well_id
GROUP BY 1
ORDER BY 1;


-- Duplicate check. If either average is above 1, any query
-- that joins straight onto these tables will double count.
SELECT
    'production rows per well' AS check_name,
    ROUND(AVG(row_count), 2)   AS average_rows,
    MAX(row_count)             AS worst_case
FROM (SELECT well_id, COUNT(*) AS row_count FROM production GROUP BY well_id) x
UNION ALL
SELECT
    'emissions rows per asset',
    ROUND(AVG(row_count), 2),
    MAX(row_count)
FROM (SELECT asset_id, COUNT(*) AS row_count FROM emissions GROUP BY asset_id) y;


-- Nulls and impossible values.
SELECT
    COUNT(*) FILTER (WHERE cost_usd IS NULL)       AS null_cost,
    COUNT(*) FILTER (WHERE cost_usd < 0)           AS negative_cost,
    COUNT(*) FILTER (WHERE downtime_hours IS NULL) AS null_downtime,
    COUNT(*) FILTER (WHERE downtime_hours < 0)     AS negative_downtime,
    COUNT(*) FILTER (WHERE failure_type IS NULL)   AS null_failure_type,
    MIN(maintenance_date)                          AS earliest_event,
    MAX(maintenance_date)                          AS latest_event
FROM maintenance;
