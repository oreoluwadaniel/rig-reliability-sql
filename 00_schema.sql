/* ============================================================
   RIGWATCH - DATABASE SETUP
   PostgreSQL 12 or later

   Run this file once before running any of the three project
   scripts. It creates the tables, loads the CSV files, and
   builds the indexes the analysis depends on.

   Why this file exists:
   The original script had no table definitions at all. It
   assumed the tables were already sitting in a database
   somewhere. That makes the work impossible for anyone else
   to reproduce, and it hid a real problem, which is that
   cost_usd was being stored as text and cast to FLOAT inside
   every query that touched it. Money should never live in a
   FLOAT column, so it is NUMERIC here.
   ============================================================ */


/* ------------------------------------------------------------
   1. CLEAN SLATE
   Dropping in reverse dependency order so re-running the file
   never fails halfway through.
------------------------------------------------------------ */

DROP VIEW  IF EXISTS v_asset_reliability CASCADE;
DROP TABLE IF EXISTS maintenance CASCADE;
DROP TABLE IF EXISTS production  CASCADE;
DROP TABLE IF EXISTS emissions   CASCADE;


/* ------------------------------------------------------------
   2. MAINTENANCE

   One row per maintenance event. 3,000 events.

   The source CSV has no unique identifier for an event, which
   means there is no safe way to count distinct failures once
   the table is joined to anything else. A surrogate key fixes
   that, and it is the single change that makes the corrected
   queries in project 03 possible.
------------------------------------------------------------ */

CREATE TABLE maintenance (
    maintenance_id    BIGSERIAL PRIMARY KEY,
    asset_id          TEXT        NOT NULL,
    maintenance_date  DATE        NOT NULL,
    cost_usd          NUMERIC(14,2),
    failure_type      TEXT,
    downtime_hours    INTEGER
);


/* ------------------------------------------------------------
   3. PRODUCTION

   Daily production readings by well. 5,000 rows.

   The CSV column is called "date". That is a type name in
   SQL, so it has been renamed to production_date. It reads
   better and it stops the query editor from colouring it as
   a keyword.
------------------------------------------------------------ */

CREATE TABLE production (
    well_id                 TEXT    NOT NULL,
    production_date         DATE    NOT NULL,
    oil_production_barrels  INTEGER,
    gas_production_mcf      INTEGER,
    water_cut_pct           NUMERIC(6,2),
    pressure_psi            INTEGER,
    temperature_c           INTEGER
);


/* ------------------------------------------------------------
   4. EMISSIONS

   Environmental readings by asset. 3,000 rows.
   Covers wells, pipelines and refineries, so it is the only
   one of the three tables that lines up with the full range
   of asset IDs found in maintenance.
------------------------------------------------------------ */

CREATE TABLE emissions (
    asset_id                TEXT    NOT NULL,
    co2_tons                NUMERIC(12,2),
    methane_leakage_tons    NUMERIC(12,2),
    energy_consumption_mwh  NUMERIC(14,2),
    reading_date            DATE
);


